// Задание 9.III: класс, вмещающий несколько объектов (5..10), двумя способами:
// КОМПОЗИЦИЯ (RobotUnit, владеет роботами) и АГРЕГАЦИЯ (RobotSquad, только
// ссылается). Время жизни вмещаемого класса наблюдается через
// QuadrupedRobot::getObjectCount() — сколько объектов класса живо прямо сейчас.
#include "robot.h"
#include "unit.h"

#include <iostream>
#include <string>
#include <vector>

namespace {

void sep(const std::string& title) {
    const size_t dashes = title.size() + 2 < 64 ? 64 - title.size() - 2 : 2;
    std::cout << "\n=== " << title << " " << std::string(dashes, '-') << "\n";
}

void alive(const std::string& where) {
    std::cout << "  >>> живых объектов QuadrupedRobot: "
              << QuadrupedRobot::getObjectCount() << "   (" << where << ")\n";
}

}  // namespace

int main() {
    alive("start");

    // ==================================================================
    sep("A. КОМПОЗИЦИЯ: отделение владеет роботами");
    // ==================================================================
    std::cout << "  состав отделения создаётся внутри отделения и не может"
                 " его пережить\n\n";
    {
        RobotUnit unit("Alpha", 6);      // 6 роботов родились вместе с отделением
        alive("после создания отделения Alpha(6)");
        unit.rollCall();

        sep("A.1 Копирование отделения = глубокая копия (новые роботы)");
        {
            RobotUnit clone(unit);
            alive("пока жива копия отделения");
            std::cout << "  uid оригинала[0] = " << unit.at(0).getUid()
                      << ", uid копии[0]  = " << clone.at(0).getUid()
                      << "  -> разные объекты\n";
        }
        alive("после уничтожения копии (её роботы умерли вместе с ней)");

        sep("A.2 Наружу отдаётся КОПИЯ, оригинал остаётся владельцу");
        QuadrupedRobot retired = unit.retirementCopy(0);
        alive("пока «отставной» робот жив");
        std::cout << "  копия: " << retired << "\n";
        std::cout << "  оригинал на месте: " << unit.at(0) << "\n";

        sep("A.3 Время жизни: что будет при выходе из блока");
        unit.rollCall();
        alive("перед выходом из блока");
    }   // ~RobotUnit -> деструкторы ВСЕХ роботов

    alive("после уничтожения отделения (роботов больше нет)");
    std::cout << "  вывод: роботы композиции умерли ровно в тот момент, когда"
                 " умерло отделение;\n"
                 "         указать на робота извне «навсегда» нельзя —"
                 " указатель на элемент стал бы висячим\n";

    // ==================================================================
    sep("B. АГРЕГАЦИЯ: отделение только ссылается на чужих роботов");
    // ==================================================================
    // Роботы созданы ВНЕШНИМ кодом и принадлежат ему.
    QuadrupedRobot rover("AGR-1", "Rover", 80.0, "standby", 0.0, nullptr);
    QuadrupedRobot scout("AGR-2", "Scout", 60.0, "standby", 0.0, nullptr);
    QuadrupedRobot mule("AGR-3", "Mule", 40.0, "standby", 0.0, nullptr);
    alive("роботы созданы внешним кодом");

    {
        RobotSquad first("Bravo");
        first.enroll(&rover);
        first.enroll(&scout);

        sep("B.1 Один и тот же робот может состоять в двух отделениях");
        RobotSquad second("Charlie");
        second.enroll(&rover);        // тот же uid, не копия
        second.enroll(&mule);
        first.rollCall();
        second.rollCall();
        std::cout << "  rover состоит в обоих: uid=" << rover.getUid()
                  << " (один объект, два отделения)\n";
        std::cout << "  повторная запись отклоняется: "
                  << (first.enroll(&rover) ? "принят" : "отказ") << "\n";

        sep("B.2 Изменение видно из обоих отделений (объект-то один)");
        first.issueCommand("march");
        std::cout << "  из второго отделения тот же робот: " << rover << "\n";

        sep("B.3 Робота можно «перевести» из отделения в отделение");
        second.discharge(&mule);
        first.enroll(&mule);
        std::cout << "  Mule переведён в Bravo; в Charlie его нет: "
                  << (second.has(&mule) ? "есть" : "нет") << "\n";

        alive("перед выходом из блока (живут squad-ы)");
    }   // ~RobotSquad: удаляется только список указателей

    alive("после уничтожения ОБОИХ отделений");
    std::cout << "  роботы живы и полностью рабочи: " << rover << "\n";
    std::cout << "  вывод: агрегация НЕ уничтожает вмещаемые объекты —"
                 " их жизнь определяет тот, кто их создал\n";

    // ==================================================================
    sep("C. Цена агрегации: висячий указатель");
    // ==================================================================
    std::vector<QuadrupedRobot*> dangling;
    {
        QuadrupedRobot temp("AGR-9", "Temp", 10.0, "standby", 0.0, nullptr);
        dangling.push_back(&temp);          // ссылка на «чужого» робота
        std::cout << "  указатель записан, робот жив: " << *dangling[0] << "\n";
    }   // temp умер; dangling[0] теперь висячий
    alive("после смерти temp");
    std::cout << "  указатель остался, объекта нет. Чтение dangling[0]->getName()"
                 " — неопределённое поведение,\n"
                 "  поэтому здесь НЕ разыменовывается. Отделение-агрегатор"
                 " обязано гарантировать, что робот переживёт его\n";

    // ==================================================================
    sep("D. Ограничение размера 5..10 (по условию задания)");
    // ==================================================================
    try {
        RobotUnit tooSmall("Delta", 3);
    } catch (const std::invalid_argument& e) {
        std::cout << "  3 робота -> исключение: " << e.what() << "\n";
    }
    try {
        RobotUnit tooBig("Echo", 11);
    } catch (const std::invalid_argument& e) {
        std::cout << "  11 роботов -> исключение: " << e.what() << "\n";
    }
    {
        RobotUnit ok("Foxtrot", RobotUnit::maxSize());   // 10 — верх границы
        alive("отделение из 10 composed-роботов");
        ok.rollCall();
    }
    alive("после уничтожения Foxtrot");

    // ==================================================================
    sep("Итог: чем композиция отличается от агрегации");
    // ==================================================================
    std::cout << "  КОМПОЗИЦИЯ (vector<QuadrupedRobot> по значению)\n"
                 "    время жизни : робот рождается и умирает вместе с"
                 " отделением\n"
                 "    владение    : одно отделение — один робот"
                 " (копия не делит)\n"
                 "    копирование : глубокое (копируются все роботы)\n"
                 "    плюсы       : невозможно получить висячий указатель,"
                 " не нужно чистить память, инвариант «5..10 роботов»"
                 " гарантируется конструктором\n"
                 "    минусы      : робота нельзя отдать наружу без копии,"
                 " нельзя состоять в двух отделениях, перестановка/копирование"
                 " дороги (см. 8.I)\n\n"
                 "  АГРЕГАЦИЯ (vector<QuadrupedRobot*>, не владеет)\n"
                 "    время жизни : независимое — отделение может умереть"
                 " раньше или позже робота\n"
                 "    владение    : у внешнего кода; отделение может быть"
                 " пустым, робот — в нескольких отделениях\n"
                 "    копирование : копируется список указателей (поверхностно),"
                 " роботы остаются общими\n"
                 "    плюсы       : робот переживает отделение, общий объект"
                 " меняют оба отделения, дёшево\n"
                 "    минусы      : риск висячего указателя и висячей"
                 " записи, нужна внешняя гарантия времени жизни\n";
    alive("конец main");
    return 0;
}
